// Widget pulpitu Androida "Notatka" (2026-11-14, plan: "widget przypiętej notatki").
// Ten sam wzorzec co plugins/withTasksWidget.js: JS (services/widgetSync.ts
// syncNoteWidget) pisze snapshot widget_note.json do filesDir i woła
// NoteWidget.requestUpdate(); provider renderuje tytuł + tekst albo do 8 pozycji listy
// (stałe sloty — RemoteViews bez kolekcji). Stuknięcie → sapp2://note?id=… (edytor).
// Wygląd z Ustawień → Widgety → Notatka: klucze "note_*" w TasksWidgetPrefs, brak →
// wspólne "bg_*". Formatowanie tekstu w widgecie pominięte (zwykły tekst).
const { withAndroidManifest, withDangerousMod, withMainApplication, AndroidConfig } = require('@expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');
const path = require('path');
const fs = require('fs');

const PROVIDER_CLASS = 'NoteWidgetProvider';
const MODULE_CLASS = 'NoteWidgetModule';
const PACKAGE_CLASS = 'NoteWidgetPackage';
const ROWS = 8;
const SCHEME = 'sapp2';

function providerKotlin(pkg) {
  const ids = (p) => Array.from({ length: ROWS }, (_, i) => `R.id.note_${p}${i}`).join(', ');
  return `package ${pkg}

import android.app.PendingIntent
import android.appwidget.AppWidgetManager
import android.appwidget.AppWidgetProvider
import android.content.ComponentName
import android.content.Context
import android.content.Intent
import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.RectF
import android.net.Uri
import android.util.TypedValue
import android.view.View
import android.widget.RemoteViews
import org.json.JSONArray
import org.json.JSONObject
import java.io.File

// Auto-generated by plugins/withNoteWidget.js — do not edit here.
class ${PROVIDER_CLASS} : AppWidgetProvider() {
  override fun onUpdate(context: Context, appWidgetManager: AppWidgetManager, appWidgetIds: IntArray) {
    updateAll(context)
  }

  companion object {
    const val FILE = "widget_note.json"
    private const val PREFS_NAME = "TasksWidgetPrefs"
    private const val ROWS = ${ROWS}
    private val ROW_IDS = intArrayOf(${ids('row')})
    private val BOX_IDS = intArrayOf(${ids('box')})
    private val TXT_IDS = intArrayOf(${ids('txt')})

    private fun readSnapshot(context: Context): JSONObject = try {
      val f = File(context.filesDir, FILE)
      if (f.exists()) JSONObject(f.readText()) else JSONObject()
    } catch (e: Exception) { JSONObject() }

    private fun bgBitmap(context: Context, argb: Int): Bitmap {
      val d = context.resources.displayMetrics.density
      val w = (300 * d).toInt().coerceAtLeast(1)
      val h = (200 * d).toInt().coerceAtLeast(1)
      val radius = 22f * d
      val bmp = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888)
      val canvas = Canvas(bmp)
      val rect = RectF(1f, 1f, w - 1f, h - 1f)
      canvas.drawRoundRect(rect, radius, radius, Paint(Paint.ANTI_ALIAS_FLAG).apply { color = argb; style = Paint.Style.FILL })
      val strokeAlpha = (Color.alpha(argb) * 0x22 / 255).coerceIn(0, 255)
      canvas.drawRoundRect(rect, radius, radius, Paint(Paint.ANTI_ALIAS_FLAG).apply {
        color = (strokeAlpha shl 24) or 0x00FFFFFF; style = Paint.Style.STROKE; strokeWidth = d
      })
      return bmp
    }

    fun updateAll(context: Context) {
      try {
        val mgr = AppWidgetManager.getInstance(context)
        val ids = mgr.getAppWidgetIds(ComponentName(context, ${PROVIDER_CLASS}::class.java))
        if (ids.isEmpty()) return
        val views = buildViews(context)
        for (id in ids) mgr.updateAppWidget(id, views)
      } catch (e: Exception) {}
    }

    private fun buildViews(context: Context): RemoteViews {
      val v = RemoteViews(context.packageName, R.layout.note_widget)
      val p = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
      val opacity = p.getInt("note_bg_opacity", p.getInt("bg_opacity", 100)).coerceIn(0, 100)
      if (opacity <= 0) {
        v.setViewVisibility(R.id.note_bg_image, View.GONE)
      } else {
        v.setViewVisibility(R.id.note_bg_image, View.VISIBLE)
        try {
          val rgb = Color.parseColor(p.getString("note_bg_color", null) ?: p.getString("bg_color", "#141414") ?: "#141414") and 0x00FFFFFF
          val argb = ((opacity * 255 / 100).coerceIn(0, 255) shl 24) or rgb
          v.setImageViewBitmap(R.id.note_bg_image, bgBitmap(context, argb))
        } catch (e: Exception) {
          v.setViewVisibility(R.id.note_bg_image, View.GONE)
        }
      }
      val mult = when (p.getString("note_text_scale", null) ?: p.getString("text_scale", "medium")) { "small" -> 0.85f; "large" -> 1.2f; else -> 1f }
      v.setTextViewTextSize(R.id.note_title, TypedValue.COMPLEX_UNIT_SP, 10f * mult)
      v.setTextViewTextSize(R.id.note_text, TypedValue.COMPLEX_UNIT_SP, 13f * mult)
      v.setTextViewTextSize(R.id.note_more, TypedValue.COMPLEX_UNIT_SP, 10f * mult)
      for (i in 0 until ROWS) v.setTextViewTextSize(TXT_IDS[i], TypedValue.COMPLEX_UNIT_SP, 13f * mult)

      val snap = readSnapshot(context)
      val noteId = snap.optString("id", "")
      val uri = if (noteId.isNotEmpty()) "${SCHEME}://note?id=" + Uri.encode(noteId) else "${SCHEME}://notes"
      val open = Intent(Intent.ACTION_VIEW, Uri.parse(uri)).apply { setPackage(context.packageName) }
      v.setOnClickPendingIntent(R.id.note_root, PendingIntent.getActivity(
        context, 3, open, PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE))

      v.setTextViewText(R.id.note_title, snap.optString("title", "NOTATKA"))
      val text = snap.optString("text", "")
      v.setViewVisibility(R.id.note_text, if (text.isNotEmpty()) View.VISIBLE else View.GONE)
      v.setTextViewText(R.id.note_text, text)
      val rows = snap.optJSONArray("rows") ?: JSONArray()
      for (i in 0 until ROWS) {
        val r = if (i < rows.length()) rows.optJSONObject(i) else null
        if (r == null) { v.setViewVisibility(ROW_IDS[i], View.GONE); continue }
        v.setViewVisibility(ROW_IDS[i], View.VISIBLE)
        val done = r.optBoolean("done", false)
        v.setTextViewText(TXT_IDS[i], r.optString("text"))
        v.setTextColor(TXT_IDS[i], Color.parseColor(if (done) "#8A8A8A" else "#F2F2F2"))
        v.setImageViewResource(BOX_IDS[i], if (done) R.drawable.note_box_done else R.drawable.note_box)
      }
      val more = snap.optInt("more", 0)
      v.setViewVisibility(R.id.note_more, if (more > 0) View.VISIBLE else View.GONE)
      v.setTextViewText(R.id.note_more, "+" + more + " więcej")
      return v
    }
  }
}
`;
}

function moduleKotlin(pkg) {
  return `package ${pkg}

import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod

// Auto-generated by plugins/withNoteWidget.js — do not edit here.
class ${MODULE_CLASS}(reactContext: ReactApplicationContext) : ReactContextBaseJavaModule(reactContext) {
  override fun getName(): String = "NoteWidget"

  @ReactMethod
  fun requestUpdate() {
    ${PROVIDER_CLASS}.updateAll(reactApplicationContext)
  }

  @ReactMethod
  fun setAppearance(opacityPct: Double, color: String, textScale: String) {
    reactApplicationContext.getSharedPreferences("TasksWidgetPrefs", android.content.Context.MODE_PRIVATE).edit()
      .putInt("note_bg_opacity", opacityPct.toInt())
      .putString("note_bg_color", color)
      .putString("note_text_scale", textScale)
      .apply()
    ${PROVIDER_CLASS}.updateAll(reactApplicationContext)
  }
}
`;
}

