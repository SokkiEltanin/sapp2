function withSources(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const pkg = (cfg.android && cfg.android.package) || 'com.sokki.sapp2';
    const javaDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...pkg.split('.'));
    fs.mkdirSync(javaDir, { recursive: true });
    fs.writeFileSync(path.join(javaDir, `${PROVIDER_CLASS}.kt`), providerKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, `${MODULE_CLASS}.kt`), moduleKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, `${PACKAGE_CLASS}.kt`), packageKotlin(pkg), 'utf8');

    const resDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
    for (const d of ['layout', 'drawable', 'xml', 'values']) fs.mkdirSync(path.join(resDir, d), { recursive: true });
    fs.writeFileSync(path.join(resDir, 'layout', 'note_widget.xml'), layoutXml(), 'utf8');
    for (const [name, xml] of Object.entries(drawables)) fs.writeFileSync(path.join(resDir, 'drawable', `${name}.xml`), xml, 'utf8');
    fs.writeFileSync(path.join(resDir, 'xml', 'note_widget_info.xml'), infoXml(), 'utf8');
    fs.writeFileSync(path.join(resDir, 'values', 'note_widget_strings.xml'),
      '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <string name="note_widget_description">Przypięta notatka albo lista</string>\n</resources>\n', 'utf8');
    return cfg;
  }]);
}

function withManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    if (!Array.isArray(app.receiver)) app.receiver = [];
    const receiverName = `.${PROVIDER_CLASS}`;
    if (!app.receiver.some((r) => r.$ && r.$['android:name'] === receiverName)) {
      app.receiver.push({
        $: { 'android:name': receiverName, 'android:exported': 'false', 'android:label': 'Notatka' },
        'intent-filter': [{ action: [{ $: { 'android:name': 'android.appwidget.action.APPWIDGET_UPDATE' } }] }],
        'meta-data': [{ $: { 'android:name': 'android.appwidget.provider', 'android:resource': '@xml/note_widget_info' } }],
      });
    }
    return cfg;
  });
}

function withPackageRegistration(config) {
  return withMainApplication(config, (cfg) => {
    cfg.modResults.contents = mergeContents({
      tag: 'sapp2-note-widget-package',
      src: cfg.modResults.contents,
      newSrc: `              add(${PACKAGE_CLASS}())`,
      anchor: /\/\/\s*add\(MyReactNativePackage\(\)\)/,
      offset: 1,
      comment: '              //',
    }).contents;
    return cfg;
  });
}

module.exports = function withNoteWidget(config) {
  config = withSources(config);
  config = withManifest(config);
  config = withPackageRegistration(config);
  return config;
};
