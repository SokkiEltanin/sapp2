// Widget pulpitu Androida "Zadania" (2026-11-13, user: "ogarnij widget zadań na
// pulpit, bo to by się w sumie przydało"; prośba z 2026-10-26 "tak jak w sapp").
// Port sapp's plugins/withTasksWidget.js — natywny Kotlin wpięty config-pluginem,
// ŚWIADOMIE bez zewnętrznej biblioteki widgetów (sapp już raz miał build-breaking
// problem z takim pakietem na SDK 54). Różnice vs sapp: tło = statyczny drawable w
// kolorze kafli sapp2 (bez sliderów przezroczystości/koloru — nikt o nie nie prosił),
// zero emotek (CLAUDE.md zasada 9), deep link `sapp2://tasks`.
//
// Przepływ: JS (services/widgetSync.ts) pisze JSON snapshot do filesDir i woła
// `TasksWidgetModule.requestUpdate()`; `TasksWidgetProvider.updateAll()` renderuje do 6
// stałych slotów RemoteViews (bez RemoteViewsService nie ma scrolla). Kółko przy
// zadaniu = "zrobione" bez otwierania appki: natywnie dopisuje id do
// widget_toggle_queue.json + chowa wiersz od razu; JS (services/widgetToggleDrain.ts)
// odhacza naprawdę przy najbliższym otwarciu appki. Tap w resztę → appka na Zadaniach.
const { withAndroidManifest, withDangerousMod, withMainApplication, AndroidConfig } = require('@expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');
const path = require('path');
const fs = require('fs');

const PROVIDER_CLASS = 'TasksWidgetProvider';
const MODULE_CLASS = 'TasksWidgetModule';
const PACKAGE_CLASS = 'TasksWidgetPackage';
const ROWS = 6;
const SCHEME = 'sapp2';

function providerKotlin(pkg) {
  const ids = (p) => Array.from({ length: ROWS }, (_, i) => `R.id.widget_${p}${i}`).join(', ');
  return `package ${pkg}

import android.app.PendingIntent
import android.appwidget.AppWidgetManager
import android.appwidget.AppWidgetProvider
import android.content.ComponentName
import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.net.Uri
import android.view.View
import android.widget.RemoteViews
import org.json.JSONArray
import org.json.JSONObject
import java.io.File

// Auto-generated by plugins/withTasksWidget.js — do not edit here.
class ${PROVIDER_CLASS} : AppWidgetProvider() {
  override fun onUpdate(context: Context, appWidgetManager: AppWidgetManager, appWidgetIds: IntArray) {
    updateAll(context)
  }

  override fun onReceive(context: Context, intent: Intent) {
    super.onReceive(context, intent)
    if (intent.action == ACTION_TOGGLE) {
      val taskId = intent.getStringExtra(EXTRA_TASK_ID)
      if (!taskId.isNullOrEmpty()) handleToggle(context, taskId)
    }
  }

  companion object {
    const val ACTION_TOGGLE = "${pkg}.WIDGET_TASK_TOGGLE"
    const val EXTRA_TASK_ID = "task_id"
    const val TASKS_FILE = "widget_tasks.json"
    const val QUEUE_FILE = "widget_toggle_queue.json"
    private const val ROWS = ${ROWS}
    private val ROW_IDS = intArrayOf(${ids('row')})
    private val DOT_IDS = intArrayOf(${ids('dot')})
    private val TITLE_IDS = intArrayOf(${ids('title')})
    private val SUB_IDS = intArrayOf(${ids('sub')})
    private val CHECK_IDS = intArrayOf(${ids('check')})

    fun updateAll(context: Context) {
      try {
        val mgr = AppWidgetManager.getInstance(context)
        val ids = mgr.getAppWidgetIds(ComponentName(context, ${PROVIDER_CLASS}::class.java))
        if (ids.isEmpty()) return
        val views = buildViews(context)
        for (id in ids) mgr.updateAppWidget(id, views)
      } catch (e: Exception) {}
    }

    private fun buildViews(context: Context): RemoteViews {
      val views = RemoteViews(context.packageName, R.layout.tasks_widget)
      val openIntent = Intent(Intent.ACTION_VIEW, Uri.parse("${SCHEME}://tasks")).apply {
        setPackage(context.packageName)
      }
      val pending = PendingIntent.getActivity(
        context, 0, openIntent,
        PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
      )
      views.setOnClickPendingIntent(R.id.widget_root, pending)

      val snap = readSnapshot(context)
      val rows = snap.optJSONArray("rows") ?: JSONArray()
      views.setTextViewText(R.id.widget_header, snap.optString("header", "ZADANIA"))
      if (rows.length() == 0) {
        views.setViewVisibility(R.id.widget_empty, View.VISIBLE)
        for (i in 0 until ROWS) views.setViewVisibility(ROW_IDS[i], View.GONE)
        return views
      }
      views.setViewVisibility(R.id.widget_empty, View.GONE)

      for (i in 0 until ROWS) {
        val row = if (i < rows.length()) rows.optJSONObject(i) else null
        if (row == null) { views.setViewVisibility(ROW_IDS[i], View.GONE); continue }
        views.setViewVisibility(ROW_IDS[i], View.VISIBLE)
        views.setTextViewText(TITLE_IDS[i], row.optString("title"))
        views.setTextViewText(SUB_IDS[i], row.optString("sub"))
        val overdue = row.optBoolean("overdue", false)
        views.setTextColor(SUB_IDS[i], if (overdue) Color.parseColor("#EF4444") else Color.parseColor("#6E6E6E"))
        try {
          views.setInt(DOT_IDS[i], "setColorFilter", Color.parseColor(row.optString("color", "#6E6E6E")))
        } catch (e: Exception) {}
        // requestCode stały PER SLOT + FLAG_UPDATE_CURRENT: przy każdym odmalowaniu
        // Android podmienia extras (nowe task_id) zamiast mnożyć PendingIntenty.
        val taskId = row.optString("id", "")
        if (taskId.isNotEmpty()) {
          val toggleIntent = Intent(context, ${PROVIDER_CLASS}::class.java).apply {
            action = ACTION_TOGGLE
            putExtra(EXTRA_TASK_ID, taskId)
          }
          val togglePending = PendingIntent.getBroadcast(
            context, 1000 + i, toggleIntent,
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
          )
          views.setOnClickPendingIntent(CHECK_IDS[i], togglePending)
        }
      }
      return views
    }

    private fun readSnapshot(context: Context): JSONObject {
      return try {
        val file = File(context.filesDir, TASKS_FILE)
        if (!file.exists()) return JSONObject()
        JSONObject(file.readText())
      } catch (e: Exception) { JSONObject() }
    }

    // Tap w kółko: id do kolejki (JS odhaczy naprawdę przy otwarciu appki) +
    // optymistycznie wiersz znika z widgetu TERAZ.
    @Synchronized
    private fun handleToggle(context: Context, taskId: String) {
      try {
        val qFile = File(context.filesDir, QUEUE_FILE)
        val qArr = if (qFile.exists()) {
          try { JSONArray(qFile.readText()) } catch (e: Exception) { JSONArray() }
        } else JSONArray()
        var already = false
        for (i in 0 until qArr.length()) if (qArr.optString(i) == taskId) { already = true; break }
        if (!already) qArr.put(taskId)
        qFile.writeText(qArr.toString())

        val tFile = File(context.filesDir, TASKS_FILE)
        if (tFile.exists()) {
          val snap = try { JSONObject(tFile.readText()) } catch (e: Exception) { JSONObject() }
          val rows = snap.optJSONArray("rows") ?: JSONArray()
          val next = JSONArray()
          for (i in 0 until rows.length()) {
            val o = rows.optJSONObject(i)
            if (o != null && o.optString("id") != taskId) next.put(o)
          }
          snap.put("rows", next)
          tFile.writeText(snap.toString())
        }
      } catch (e: Exception) {}
      updateAll(context)
    }
  }
}
`;
}

