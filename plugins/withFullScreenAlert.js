// full-screen-intent powiadomień jak budzik/połączenie przychodzące).
//
// WERSJA 2 (2026-10-30) — user złapał na urządzeniu: "cała aplikacja się buguje,
// działa na OFFSCREENIE CAŁA... nie chcę żeby ktoś na zablokowanym telefonie mógł
// [finanse] przeglądać". Wersja 1 ustawiała `android:showWhenLocked`/
// `android:turnScreenOn` na STAŁE w manifeście na MainActivity — a że cała appka
// (expo-router) żyje w JEDNEJ Activity, to oznaczało że CAŁA appka, nie tylko
// ekran alarmu, omijała blokadę ekranu przy każdym wznowieniu. Realna dziura
// bezpieczeństwa (dokładnie to ryzyko było już opisane w komentarzu tej wersji 1,
// "do oceny po teście, nie ukrywać" — i potwierdziło się).
//
// Fix: ZERO statycznych flag na Activity. Zamiast tego natywny moduł
// `LockScreenModule` przełącza `Activity.setShowWhenLocked()`/`setTurnScreenOn()`
// W LOCIE (API 27+, dokładnie po to Android to dodał — pokazywanie KONKRETNEGO
// ekranu nad blokadą, nie całej appki) — wołany z JS WYŁĄCZNIE na czas
// wyświetlania app/alert-test.tsx (patrz src/services/lockScreen.ts), i
// wyłączany natychmiast przy zejściu z tego ekranu. Ten sam wzorzec
// wstrzykiwania natywnego Kotlina przez config-plugin co `withTasksWidget.js` w
// sapp (`withDangerousMod` + `withMainApplication`/`mergeContents`).
const { withMainApplication, withDangerousMod } = require('@expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');
const path = require('path');
const fs = require('fs');

const MODULE_CLASS = 'LockScreenModule';
const PACKAGE_CLASS = 'LockScreenPackage';

function moduleKotlin(pkg) {
  return `package ${pkg}

import android.os.Build
import android.view.WindowManager
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod

// Auto-generated by plugins/withFullScreenAlert.js — do not edit here.
// Przełącza "pokaż nad blokadą ekranu" W LOCIE dla BIEŻĄCEJ Activity — NIGDY nie
// ustawiać tego na stałe w manifeście (patrz komentarz w withFullScreenAlert.js).
class ${MODULE_CLASS}(reactContext: ReactApplicationContext) : ReactContextBaseJavaModule(reactContext) {
  override fun getName(): String = "LockScreen"

  @ReactMethod
  fun setShowOverLockScreen(enabled: Boolean) {
    val activity = reactApplicationContext.currentActivity ?: return
    activity.runOnUiThread {
      if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O_MR1) {
        activity.setShowWhenLocked(enabled)
        activity.setTurnScreenOn(enabled)
      } else {
        @Suppress("DEPRECATION")
        if (enabled) {
          activity.window.addFlags(
            WindowManager.LayoutParams.FLAG_SHOW_WHEN_LOCKED or WindowManager.LayoutParams.FLAG_TURN_SCREEN_ON
          )
        } else {
          activity.window.clearFlags(
            WindowManager.LayoutParams.FLAG_SHOW_WHEN_LOCKED or WindowManager.LayoutParams.FLAG_TURN_SCREEN_ON
          )
        }
      }
    }
  }
}
`;
}

function packageKotlin(pkg) {
  return `package ${pkg}

import com.facebook.react.ReactPackage
import com.facebook.react.bridge.NativeModule
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.uimanager.ViewManager

// Auto-generated by plugins/withFullScreenAlert.js — do not edit here.
class ${PACKAGE_CLASS} : ReactPackage {
  override fun createNativeModules(reactContext: ReactApplicationContext): List<NativeModule> =
    listOf(${MODULE_CLASS}(reactContext))

  override fun createViewManagers(reactContext: ReactApplicationContext): List<ViewManager<*, *>> =
    emptyList()
}
`;
}

function withSources(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const pkg = (cfg.android && cfg.android.package) || 'com.sokki.sapp2';
    const javaDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...pkg.split('.'));
    fs.mkdirSync(javaDir, { recursive: true });
    fs.writeFileSync(path.join(javaDir, `${MODULE_CLASS}.kt`), moduleKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, `${PACKAGE_CLASS}.kt`), packageKotlin(pkg), 'utf8');
    return cfg;
  }]);
}

// Rejestruje LockScreenPackage w getPackages() — ten sam mechanizm (mergeContents
// z markerem, idempotentny między prebuildami) co withTasksWidget.js w sapp.
function withPackageRegistration(config) {
  return withMainApplication(config, (cfg) => {
    cfg.modResults.contents = mergeContents({
      tag: 'sapp2-lock-screen-package',
      src: cfg.modResults.contents,
      newSrc: `              add(${PACKAGE_CLASS}())`,
      anchor: /\/\/\s*add\(MyReactNativePackage\(\)\)/,
      offset: 1,
      comment: '              //',
    }).contents;
    return cfg;
  });
}

module.exports = function withFullScreenAlert(config) {
  config = withSources(config);
  config = withPackageRegistration(config);
  return config;
};
