// Przycisk S-Pena (2026-11-18, user: "jak jest przycisk na S-Penie, to czy on może włączać
// gumkę?"). react-native-gesture-handler daje pointerType i nacisk, ale NIE stan przycisku
// rysika — ten jest tylko w natywnym MotionEvent.getButtonState() (BUTTON_STYLUS_PRIMARY,
// Samsung zgłasza go, gdy przycisk jest wciśnięty i rysik dotyka ekranu).
// MainActivity.dispatchTouchEvent zapisuje ostatni stan do StylusState (przed RN, więc gdy
// gest w JS startuje, stan już jest), a StylusModule.isButtonDown() czyta go synchronicznie.
// JS: components/notes/DrawingCanvas.tsx (`?.` — stary APK = brak modułu = bez gumki z przycisku).
const { withMainActivity, withDangerousMod, withMainApplication } = require('@expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');
const path = require('path');
const fs = require('fs');

function stateKotlin(pkg) {
  return `package ${pkg}

import android.view.MotionEvent

// Auto-generated by plugins/withStylus.js — do not edit here.
object StylusState {
  @Volatile var buttonDown: Boolean = false
  @Volatile var lastTool: Int = MotionEvent.TOOL_TYPE_UNKNOWN

  fun update(ev: MotionEvent) {
    try {
      val tool = ev.getToolType(0)
      lastTool = tool
      if (ev.actionMasked == MotionEvent.ACTION_UP || ev.actionMasked == MotionEvent.ACTION_CANCEL) {
        // stan z kreski zostaje do następnego dotknięcia (JS czyta go na starcie kreski)
        return
      }
      if (tool == MotionEvent.TOOL_TYPE_STYLUS || tool == MotionEvent.TOOL_TYPE_ERASER) {
        val b = ev.buttonState
        buttonDown = tool == MotionEvent.TOOL_TYPE_ERASER ||
          (b and MotionEvent.BUTTON_STYLUS_PRIMARY) != 0 ||
          (b and MotionEvent.BUTTON_SECONDARY) != 0
      } else {
        buttonDown = false
      }
    } catch (e: Throwable) {}
  }
}
`;
}

function moduleKotlin(pkg) {
  return `package ${pkg}

import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod

// Auto-generated by plugins/withStylus.js — do not edit here.
class StylusModule(reactContext: ReactApplicationContext) : ReactContextBaseJavaModule(reactContext) {
  override fun getName(): String = "Stylus"

  @ReactMethod(isBlockingSynchronousMethod = true)
  fun isButtonDown(): Boolean = StylusState.buttonDown
}
`;
}

function packageKotlin(pkg) {
  return `package ${pkg}

import com.facebook.react.ReactPackage
import com.facebook.react.bridge.NativeModule
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.uimanager.ViewManager

// Auto-generated by plugins/withStylus.js — do not edit here.
class StylusPackage : ReactPackage {
  override fun createNativeModules(reactContext: ReactApplicationContext): List<NativeModule> =
    listOf(StylusModule(reactContext))

  override fun createViewManagers(reactContext: ReactApplicationContext): List<ViewManager<*, *>> =
    emptyList()
}
`;
}

function withSources(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const pkg = (cfg.android && cfg.android.package) || 'com.sokki.sapp2';
    const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...pkg.split('.'));
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'StylusState.kt'), stateKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(dir, 'StylusModule.kt'), moduleKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(dir, 'StylusPackage.kt'), packageKotlin(pkg), 'utf8');
    return cfg;
  }]);
}

const IMPORT = 'import android.view.MotionEvent';
const OVERRIDE = `  // plugins/withStylus.js — stan przycisku S-Pena dla notatek
  override fun dispatchTouchEvent(ev: MotionEvent): Boolean {
    StylusState.update(ev)
    return super.dispatchTouchEvent(ev)
  }
`;

function withActivity(config) {
  return withMainActivity(config, (cfg) => {
    if (cfg.modResults.language !== 'kt') return cfg;
    let src = cfg.modResults.contents;
    if (!src.includes(IMPORT)) src = src.replace(/(^package .*$)/m, `$1\n\n${IMPORT}`);
    if (!src.includes('StylusState.update(ev)')) {
      src = src.replace(/(class MainActivity\s*:\s*ReactActivity\(\)\s*\{\s*\n)/, `$1${OVERRIDE}\n`);
    }
    cfg.modResults.contents = src;
    return cfg;
  });
}

function withPackageRegistration(config) {
  return withMainApplication(config, (cfg) => {
    cfg.modResults.contents = mergeContents({
      tag: 'sapp2-stylus-package',
      src: cfg.modResults.contents,
      newSrc: '              add(StylusPackage())',
      anchor: /\/\/\s*add\(MyReactNativePackage\(\)\)/,
      offset: 1,
      comment: '              //',
    }).contents;
    return cfg;
  });
}

module.exports = function withStylus(config) {
  return withPackageRegistration(withActivity(withSources(config)));
};
