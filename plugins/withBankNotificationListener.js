// Port z sapp (plugins/withBankNotificationListener.js) 1:1 — przechwytuje push'e z
// banku BEZ zewnętrznej zależności: minimalny Kotlinowy NotificationListenerService
// wstrzyknięty prosto do wygenerowanego projektu Android i zadeklarowany w manifeście.
// Filtruje do apek bankowych, dopisuje {title,text,pkg,time} do pliku JSON w `filesDir`
// appki. Strona JS (src/services/bankNotificationDrain.ts) czyta ten plik — to to samo
// miejsce co expo-file-system's `documentDirectory` — przy każdym wejściu appki na
// pierwszy plan i przepuszcza przez istniejący pipeline ingest → kolejka →
// auto-akceptacja.
//
// Custom zamiast react-native-android-notification-listener — ten sam powód co w sapp:
// unika przestarzałego AGP-8 `namespace` build-breaku na SDK 54 i trzyma każdy ruchomy
// element pod naszą kontrolą. User wciąż musi RĘCZNIE przyznać "Dostęp do powiadomień"
// (raz, przycisk w Ustawieniach otwiera ten systemowy ekran).
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('@expo/config-plugins');
const path = require('path');
const fs = require('fs');

const SERVICE_CLASS = 'Sapp2NotificationListener';

// Apki bankowe, których powiadomień słuchamy — zsynchronizowane z BANK_PACKAGES w
// src/utils/bankNotification.ts.
const BANK_PACKAGES = ['pl.pekao24.peopay', 'eu.eleader.mobilebanking.pekao', 'pl.pkobp.iko'];

function kotlinSource(pkg) {
  const pkgSet = BANK_PACKAGES.map((p) => `"${p}"`).join(', ');
  return `package ${pkg}

import android.app.Notification
import android.content.ComponentName
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import org.json.JSONArray
import org.json.JSONObject
import java.io.File

// Auto-generated by plugins/withBankNotificationListener.js — do not edit here.
class ${SERVICE_CLASS} : NotificationListenerService() {

  private val bankPackages = setOf(${pkgSet})

  override fun onNotificationPosted(sbn: StatusBarNotification?) {
    handle(sbn)
  }

  // Drugi punkt przechwytu: jeśli usługa spała (OEM battery-saver) gdy powiadomienie
  // się POJAWIŁO, onNotificationPosted nigdy nie odpalił — jedynym ratunkiem było
  // onListenerConnected zamiatające to co WCIĄŻ jest w zasobniku. Jeśli user odrzuci je
  // zanim usługa się obudzi, ten sweep nic nie znajdzie i wydatek przepada na zawsze.
  // Obsługa tutaj też zamienia "odrzucone zanim się obudziliśmy" w drugą szansę zamiast
  // martwego punktu — dedup w append() (czas+tytuł+treść) chroni przed podwójnym
  // zliczeniem gdyby oba callbacki i tak odpaliły dla tego samego.
  override fun onNotificationRemoved(sbn: StatusBarNotification?) {
    handle(sbn)
  }

  // Gdy system (ponownie) podpina nasłuch — np. po zabiciu go przez OEM battery-saver i
  // powrocie — zamiata wszystkie powiadomienia bankowe wciąż widoczne w zasobniku, żeby
  // zabicie usługi cicho nie zgubiło tych które przyszły gdy była martwa.
  override fun onListenerConnected() {
    try {
      val active = activeNotifications ?: return
      for (sbn in active) handle(sbn)
    } catch (e: Exception) {}
  }

  // Jeśli nas odłączono, grzecznie poproś system o ponowne podpięcie.
  override fun onListenerDisconnected() {
    try { requestRebind(ComponentName(this, ${SERVICE_CLASS}::class.java)) } catch (e: Exception) {}
  }

  private fun handle(sbn: StatusBarNotification?) {
    try {
      val n = sbn ?: return
      val pkg = n.packageName ?: return
      noteSeen(pkg)   // diagnostyka: zapisz każdą apkę, z której powiadomienie do nas dotarło
      val extras = n.notification?.extras ?: return
      val title = extras.getCharSequence(Notification.EXTRA_TITLE)?.toString() ?: ""
      val text = (extras.getCharSequence(Notification.EXTRA_TEXT)
        ?: extras.getCharSequence(Notification.EXTRA_BIG_TEXT))?.toString() ?: ""
      if (title.isEmpty() && text.isEmpty()) return
      // Przechwytujemy jeśli to znana apka bankowa LUB TREŚĆ wygląda jak płatność z
      // banku. Druga ścieżka to siatka bezpieczeństwa gdy nazwa pakietu apki bankowej
      // nie jest na naszej sztywnej liście (parser JS to i tak ostateczna bramka, śmieci
      // są odrzucane tam).
      if (!bankPackages.contains(pkg) && !looksLikeBankPayment(title + " " + text)) return
      append(pkg, title, text, n.postTime)
    } catch (e: Exception) {}
  }

  // Beznaciskowy sniff treści dla pushu płatności Pekao/PeoPay. Celowo szeroki dla nazwy
  // banku ("pekao"/"peopay" pojawiają się w każdym ich powiadomieniu), żeby zła nazwa
  // pakietu nie ukryła prawdziwej płatności; węższy poza tym żeby uniknąć szumu.
  private fun looksLikeBankPayment(body: String): Boolean {
    val b = body.lowercase()
    if (b.contains("pekao") || b.contains("peopay")) return true
    val money = b.contains("pln") || b.contains("eur")
    val ctx = b.contains("kwot") || b.contains("konto") || b.contains("transakcj") ||
      b.contains("blik") || b.contains("przelew")
    return money && ctx
  }

  // Zapisuje zbiór pakietów które widzieliśmy (bez duplikatów, capped) — żeby
  // diagnostyka w appce mogła pokazać czy nasłuch w ogóle coś odbiera, i jaki jest
  // prawdziwy pakiet PeoPay (żeby dało się dodać go do listy przechwytu).
  @Synchronized
  private fun noteSeen(pkg: String) {
    try {
      val file = File(filesDir, SEEN_FILE)
      val arr = if (file.exists()) {
        try { JSONArray(file.readText()) } catch (e: Exception) { JSONArray() }
      } else JSONArray()
      for (i in 0 until arr.length()) if (arr.optString(i) == pkg) return
      arr.put(pkg)
      val out = if (arr.length() > 40) {
        val t = JSONArray()
        for (i in (arr.length() - 40) until arr.length()) t.put(arr.get(i))
        t
      } else arr
      file.writeText(out.toString())
    } catch (e: Exception) {}
  }

  @Synchronized
  private fun append(pkg: String, title: String, text: String, time: Long) {
    try {
      val file = File(filesDir, FILE_NAME)
      val arr = if (file.exists()) {
        try { JSONArray(file.readText()) } catch (e: Exception) { JSONArray() }
      } else JSONArray()
      // dedup: reconnect sweep może ponownie zobaczyć powiadomienie które już zapisaliśmy
      for (i in 0 until arr.length()) {
        val o = arr.optJSONObject(i) ?: continue
        if (o.optLong("time") == time && o.optString("title") == title && o.optString("text") == text) return
      }
      val obj = JSONObject()
      obj.put("pkg", pkg)
      obj.put("title", title)
      obj.put("text", text)
      obj.put("time", time)
      arr.put(obj)
      val out = if (arr.length() > MAX) {
        val t = JSONArray()
        for (i in (arr.length() - MAX) until arr.length()) t.put(arr.get(i))
        t
      } else arr
      file.writeText(out.toString())
    } catch (e: Exception) {}
  }

  companion object {
    const val FILE_NAME = "bank_notifications.json"
    const val SEEN_FILE = "seen_packages.json"
    const val MAX = 50
  }
}
`;
}

function withServiceSource(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const pkg = (cfg.android && cfg.android.package) || 'com.sokki.sapp2';
    const javaDir = path.join(
      cfg.modRequest.platformProjectRoot,
      'app', 'src', 'main', 'java', ...pkg.split('.'),
    );
    fs.mkdirSync(javaDir, { recursive: true });
    fs.writeFileSync(path.join(javaDir, `${SERVICE_CLASS}.kt`), kotlinSource(pkg), 'utf8');
    return cfg;
  }]);
}

function withServiceManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    if (!Array.isArray(app.service)) app.service = [];
    const name = `.${SERVICE_CLASS}`;
    if (app.service.some((s) => s.$ && s.$['android:name'] === name)) return cfg;
    app.service.push({
      $: {
        'android:name': name,
        'android:label': 'Sapp2 — powiadomienia',
        'android:exported': 'true',
        'android:permission': 'android.permission.BIND_NOTIFICATION_LISTENER_SERVICE',
      },
      'intent-filter': [
        { action: [{ $: { 'android:name': 'android.service.notification.NotificationListenerService' } }] },
      ],
    });
    return cfg;
  });
}

module.exports = function withBankNotificationListener(config) {
  config = withServiceSource(config);
  config = withServiceManifest(config);
  return config;
};
