// Most telefon ↔ zegarek Wear OS (2026-11-14, user: "na Wear OS tylko basic rzeczy:
// ostatnie wydatki, dzisiejsze zadania"). Wear Data Layer (Google Play Services):
//  • telefon → zegarek: JS (services/wearSync.ts) woła WearSync.push(json) → DataItem
//    "/sapp2/snapshot" (zegarek dostaje go też, gdy był poza zasięgiem — Data Layer
//    dosyła sam). Treść: src/utils/wearSnapshot.ts.
//  • zegarek → telefon: bateria = DataItem "/sapp2/battery" (2026-11-16, powiadomienie
//    przy niskim poziomie); odhaczenie zadania = wiadomość "/sapp2/toggle" z id zadania;
//    WearListenerService dopisuje id do widget_toggle_queue.json (ta sama kolejka co
//    widget Zadań), appka odhacza przy najbliższym otwarciu (widgetToggleDrain.ts).
// Aplikacja zegarka: katalog wear/ (osobny projekt Gradle, ten sam applicationId i
// klucz podpisu — inaczej Data Layer nie połączy telefonu z zegarkiem).
const { withAndroidManifest, withDangerousMod, withMainApplication, withAppBuildGradle, AndroidConfig } = require('@expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');
const path = require('path');
const fs = require('fs');

const WEARABLE_DEP = 'com.google.android.gms:play-services-wearable:18.2.0';

function moduleKotlin(pkg) {
  return `package ${pkg}

import android.net.Uri
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod
import com.google.android.gms.wearable.PutDataMapRequest
import com.google.android.gms.wearable.Wearable

// Auto-generated by plugins/withWearSync.js — do not edit here.
class WearSyncModule(reactContext: ReactApplicationContext) : ReactContextBaseJavaModule(reactContext) {
  override fun getName(): String = "WearSync"

  @ReactMethod
  fun push(json: String) {
    try {
      val req = PutDataMapRequest.create("/sapp2/snapshot").apply {
        dataMap.putString("json", json)
        dataMap.putLong("t", System.currentTimeMillis())
      }.asPutDataRequest().setUrgent()
      Wearable.getDataClient(reactApplicationContext).putDataItem(req)
    } catch (e: Exception) {}
  }

  // Próbka baterii TELEFONU do historii (2026-11-17) — JS woła przy zmianie poziomu, a
  // WearListenerService przy każdym raporcie zegarka (co ~15 min, też gdy appka zamknięta).
  @ReactMethod
  fun samplePhone() {
    try { BatteryLog.samplePhone(reactApplicationContext) } catch (e: Exception) {}
  }

  // Prośba do zegarka o świeży stan baterii (2026-11-16) — odpowiedź przychodzi jako
  // DataItem "/sapp2/battery" do WearListenerService (zapis do wear_battery.json).
  @ReactMethod
  fun requestBattery() {
    try {
      val ctx = reactApplicationContext
      Wearable.getNodeClient(ctx).connectedNodes.addOnSuccessListener { nodes ->
        for (n in nodes) Wearable.getMessageClient(ctx).sendMessage(n.id, "/sapp2/battery-req", ByteArray(0))
      }
    } catch (e: Exception) {}
  }
}
`;
}

