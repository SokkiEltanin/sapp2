function serviceKotlin(pkg) {
  return `package ${pkg}

import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.content.IntentFilter
import android.os.BatteryManager
import android.os.Build
import androidx.core.app.NotificationCompat
import com.google.android.gms.wearable.DataEvent
import com.google.android.gms.wearable.DataEventBuffer
import com.google.android.gms.wearable.DataMapItem
import com.google.android.gms.wearable.MessageEvent
import com.google.android.gms.wearable.WearableListenerService
import org.json.JSONArray
import org.json.JSONObject
import java.io.File

// Auto-generated by plugins/withWearSync.js — do not edit here.
// • "/sapp2/toggle" (wiadomość): odhaczenie zadania → kolejka odhaczeń (wspólna z widgetem).
// • "/sapp2/battery" (DataItem, 2026-11-16): bateria zegarka → wear_battery.json (JS czyta
//   go w services/watchBattery.ts) + powiadomienie "podładuj zegarek" poniżej progu
//   (wear_battery_cfg.json z JS; raz na rozładowanie — reset po ładowaniu).
// Historia baterii (2026-11-17, user: "ile, kiedy ostatnio ładowane, temperatura, wykresy,
// zużycie od ostatniego ładowania"): JSON [{t,l,c,tp}] — ostatnie ~4 dni. Telefon dopisuje
// zegarek przy każdym jego raporcie i przy okazji SIEBIE (temperatura tylko natywnie).
object BatteryLog {
  private const val MAX = 400
  private const val KEEP_MS = 4L * 24 * 3600 * 1000

  @Synchronized
  fun append(ctx: Context, file: String, level: Int, charging: Boolean, temp: Double?, t: Long) {
    try {
      val f = File(ctx.filesDir, file)
      val arr = if (f.exists()) try { JSONArray(f.readText()) } catch (e: Exception) { JSONArray() } else JSONArray()
      if (arr.length() > 0) {
        val last = arr.getJSONObject(arr.length() - 1)
        // ten sam stan w ciągu 5 min — nie dubluj (zegarek raportuje też na żądanie)
        if (t - last.optLong("t") < 5 * 60 * 1000 && last.optInt("l") == level && last.optBoolean("c") == charging) return
      }
      val o = JSONObject().put("t", t).put("l", level).put("c", charging)
      if (temp != null) o.put("tp", Math.round(temp * 10) / 10.0)
      arr.put(o)
      val out = JSONArray()
      val from = Math.max(0, arr.length() - MAX)
      for (i in from until arr.length()) { val x = arr.getJSONObject(i); if (t - x.optLong("t") <= KEEP_MS) out.put(x) }
      f.writeText(out.toString())
    } catch (e: Exception) {}
  }

  fun samplePhone(ctx: Context) {
    val i = ctx.registerReceiver(null, IntentFilter(Intent.ACTION_BATTERY_CHANGED)) ?: return
    val level = i.getIntExtra(BatteryManager.EXTRA_LEVEL, -1)
    val scale = i.getIntExtra(BatteryManager.EXTRA_SCALE, 100)
    if (level < 0 || scale <= 0) return
    val status = i.getIntExtra(BatteryManager.EXTRA_STATUS, -1)
    val charging = status == BatteryManager.BATTERY_STATUS_CHARGING || status == BatteryManager.BATTERY_STATUS_FULL
    val tRaw = i.getIntExtra(BatteryManager.EXTRA_TEMPERATURE, Int.MIN_VALUE)
    val temp = if (tRaw == Int.MIN_VALUE) null else tRaw / 10.0
    append(ctx, "battery_log_phone.json", Math.round(level * 100f / scale), charging, temp, System.currentTimeMillis())
  }
}

class WearListenerService : WearableListenerService() {
  override fun onMessageReceived(event: MessageEvent) {
    // Krok zadania odhaczony na zegarku (2026-11-16): "taskId|stepId|1/0" → kolejka,
    // appka stosuje ją przy otwarciu (services/widgetToggleDrain.ts).
    if (event.path == "/sapp2/step") {
      val msg = String(event.data, Charsets.UTF_8).trim()
      if (msg.isEmpty()) return
      try {
        val f = File(filesDir, "wear_step_queue.json")
        val arr = if (f.exists()) try { JSONArray(f.readText()) } catch (e: Exception) { JSONArray() } else JSONArray()
        arr.put(msg)
        f.writeText(arr.toString())
      } catch (e: Exception) {}
      return
    }
    if (event.path != "/sapp2/toggle") return
    val taskId = String(event.data, Charsets.UTF_8).trim()
    if (taskId.isEmpty()) return
    try {
      val f = File(filesDir, "widget_toggle_queue.json")
      val arr = if (f.exists()) try { JSONArray(f.readText()) } catch (e: Exception) { JSONArray() } else JSONArray()
      var already = false
      for (i in 0 until arr.length()) if (arr.optString(i) == taskId) { already = true; break }
      if (!already) arr.put(taskId)
      f.writeText(arr.toString())
    } catch (e: Exception) {}
  }

  override fun onDataChanged(events: DataEventBuffer) {
    for (e in events) {
      if (e.type != DataEvent.TYPE_CHANGED || e.dataItem.uri.path != "/sapp2/battery") continue
      try {
        val m = DataMapItem.fromDataItem(e.dataItem).dataMap
        val level = m.getInt("level", -1)
        if (level < 0) continue
        val charging = m.getBoolean("charging", false)
        val temp = m.getFloat("temp", -100f)
        val t = m.getLong("t", System.currentTimeMillis())
        val json = JSONObject()
          .put("level", level).put("charging", charging)
          .put("model", m.getString("model") ?: "").put("t", t)
        if (temp > -50f) json.put("temp", temp.toDouble())
        File(filesDir, "wear_battery.json").writeText(json.toString())
        BatteryLog.append(this, "battery_log_watch.json", level, charging, if (temp > -50f) temp.toDouble() else null, t)
        BatteryLog.samplePhone(this)
        maybeNotify(level, charging)
      } catch (ex: Exception) {}
    }
  }

  private fun maybeNotify(level: Int, charging: Boolean) {
    var low = 20
    var enabled = true
    try {
      val f = File(filesDir, "wear_battery_cfg.json")
      if (f.exists()) { val c = JSONObject(f.readText()); low = c.optInt("lowPct", 20); enabled = c.optBoolean("notify", true) }
    } catch (e: Exception) {}
    val prefs = getSharedPreferences("wear_battery", Context.MODE_PRIVATE)
    val notified = prefs.getBoolean("notified", false)
    if (charging || level > low + 5) { if (notified) prefs.edit().putBoolean("notified", false).apply(); return }
    if (!enabled || notified || level > low) return
    prefs.edit().putBoolean("notified", true).apply()
    try {
      val nm = getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager
      if (Build.VERSION.SDK_INT >= 26 && nm.getNotificationChannel("watch_battery") == null) {
        nm.createNotificationChannel(NotificationChannel("watch_battery", "Bateria zegarka", NotificationManager.IMPORTANCE_DEFAULT))
      }
      val launch = packageManager.getLaunchIntentForPackage(packageName)
      val pi = if (launch != null) PendingIntent.getActivity(this, 4200, launch, PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE) else null
      var icon = resources.getIdentifier("notification_icon", "drawable", packageName)
      if (icon == 0) icon = applicationInfo.icon
      val n = NotificationCompat.Builder(this, "watch_battery")
        .setSmallIcon(icon)
        .setContentTitle("Zegarek: " + level + "% baterii")
        .setContentText("Podładuj zegarek, zanim się rozładuje.")
        .setAutoCancel(true)
        .apply { if (pi != null) setContentIntent(pi) }
        .build()
      nm.notify(4200, n)
    } catch (e: Exception) {}
  }
}
`;
}

function withSources(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const pkg = (cfg.android && cfg.android.package) || 'com.sokki.sapp2';
    const javaDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...pkg.split('.'));
    fs.mkdirSync(javaDir, { recursive: true });
    fs.writeFileSync(path.join(javaDir, 'WearSyncModule.kt'), moduleKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, 'WearSyncPackage.kt'), packageKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, 'WearListenerService.kt'), serviceKotlin(pkg), 'utf8');
    return cfg;
  }]);
}

function withDependency(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (!cfg.modResults.contents.includes('play-services-wearable')) {
      cfg.modResults.contents = cfg.modResults.contents.replace(
        /dependencies\s*\{/,
        `dependencies {\n    implementation("${WEARABLE_DEP}")`,
      );
    }
    return cfg;
  });
}

function withManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    if (!Array.isArray(app.service)) app.service = [];
    // Wiadomości (odhaczenia) + dane (bateria zegarka, 2026-11-16).
    app.service = app.service.filter((x) => !(x.$ && x.$['android:name'] === '.WearListenerService'));
    const wearData = [{ $: { 'android:scheme': 'wear', 'android:host': '*', 'android:pathPrefix': '/sapp2' } }];
    app.service.push({
      $: { 'android:name': '.WearListenerService', 'android:exported': 'true' },
      'intent-filter': [
        { action: [{ $: { 'android:name': 'com.google.android.gms.wearable.MESSAGE_RECEIVED' } }], data: wearData },
        { action: [{ $: { 'android:name': 'com.google.android.gms.wearable.DATA_CHANGED' } }], data: wearData },
      ],
    });
    return cfg;
  });
}

function withPackageRegistration(config) {
  return withMainApplication(config, (cfg) => {
    cfg.modResults.contents = mergeContents({
      tag: 'sapp2-wear-sync-package',
      src: cfg.modResults.contents,
      newSrc: '              add(WearSyncPackage())',
      anchor: /\/\/\s*add\(MyReactNativePackage\(\)\)/,
      offset: 1,
      comment: '              //',
    }).contents;
    return cfg;
  });
}

module.exports = function withWearSync(config) {
  config = withSources(config);
  config = withDependency(config);
  config = withManifest(config);
  config = withPackageRegistration(config);
  return config;
};
