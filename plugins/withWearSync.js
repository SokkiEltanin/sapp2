// Most telefon ↔ zegarek Wear OS (2026-11-14, user: "na Wear OS tylko basic rzeczy:
// ostatnie wydatki, dzisiejsze zadania"). Wear Data Layer (Google Play Services):
//  • telefon → zegarek: JS (services/wearSync.ts) woła WearSync.push(json) → DataItem
//    "/sapp2/snapshot" (zegarek dostaje go też, gdy był poza zasięgiem — Data Layer
//    dosyła sam). Treść: src/utils/wearSnapshot.ts.
//  • zegarek → telefon: odhaczenie zadania = wiadomość "/sapp2/toggle" z id zadania;
//    WearListenerService dopisuje id do widget_toggle_queue.json (ta sama kolejka co
//    widget Zadań), appka odhacza przy najbliższym otwarciu (widgetToggleDrain.ts).
// Aplikacja zegarka: katalog wear/ (osobny projekt Gradle, ten sam applicationId i
// klucz podpisu — inaczej Data Layer nie połączy telefonu z zegarkiem).
const { withAndroidManifest, withDangerousMod, withMainApplication, withAppBuildGradle, AndroidConfig } = require('@expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');
const path = require('path');
const fs = require('fs');

const WEARABLE_DEP = 'com.google.android.gms:play-services-wearable:18.2.0';

function moduleKotlin(pkg) {
  return `package ${pkg}

import android.net.Uri
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod
import com.google.android.gms.wearable.PutDataMapRequest
import com.google.android.gms.wearable.Wearable

// Auto-generated by plugins/withWearSync.js — do not edit here.
class WearSyncModule(reactContext: ReactApplicationContext) : ReactContextBaseJavaModule(reactContext) {
  override fun getName(): String = "WearSync"

  @ReactMethod
  fun push(json: String) {
    try {
      val req = PutDataMapRequest.create("/sapp2/snapshot").apply {
        dataMap.putString("json", json)
        dataMap.putLong("t", System.currentTimeMillis())
      }.asPutDataRequest().setUrgent()
      Wearable.getDataClient(reactApplicationContext).putDataItem(req)
    } catch (e: Exception) {}
  }
}
`;
}

function packageKotlin(pkg) {
  return `package ${pkg}

import com.facebook.react.ReactPackage
import com.facebook.react.bridge.NativeModule
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.uimanager.ViewManager

// Auto-generated by plugins/withWearSync.js — do not edit here.
class WearSyncPackage : ReactPackage {
  override fun createNativeModules(reactContext: ReactApplicationContext): List<NativeModule> =
    listOf(WearSyncModule(reactContext))

  override fun createViewManagers(reactContext: ReactApplicationContext): List<ViewManager<*, *>> =
    emptyList()
}
`;
}

function serviceKotlin(pkg) {
  return `package ${pkg}

import com.google.android.gms.wearable.MessageEvent
import com.google.android.gms.wearable.WearableListenerService
import org.json.JSONArray
import java.io.File

// Auto-generated by plugins/withWearSync.js — do not edit here.
// Odhaczenie zadania na zegarku → kolejka odhaczeń (wspólna z widgetem Zadań).
class WearListenerService : WearableListenerService() {
  override fun onMessageReceived(event: MessageEvent) {
    if (event.path != "/sapp2/toggle") return
    val taskId = String(event.data, Charsets.UTF_8).trim()
    if (taskId.isEmpty()) return
    try {
      val f = File(filesDir, "widget_toggle_queue.json")
      val arr = if (f.exists()) try { JSONArray(f.readText()) } catch (e: Exception) { JSONArray() } else JSONArray()
      var already = false
      for (i in 0 until arr.length()) if (arr.optString(i) == taskId) { already = true; break }
      if (!already) arr.put(taskId)
      f.writeText(arr.toString())
    } catch (e: Exception) {}
  }
}
`;
}

function withSources(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const pkg = (cfg.android && cfg.android.package) || 'com.sokki.sapp2';
    const javaDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...pkg.split('.'));
    fs.mkdirSync(javaDir, { recursive: true });
    fs.writeFileSync(path.join(javaDir, 'WearSyncModule.kt'), moduleKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, 'WearSyncPackage.kt'), packageKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(javaDir, 'WearListenerService.kt'), serviceKotlin(pkg), 'utf8');
    return cfg;
  }]);
}

function withDependency(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (!cfg.modResults.contents.includes('play-services-wearable')) {
      cfg.modResults.contents = cfg.modResults.contents.replace(
        /dependencies\s*\{/,
        `dependencies {\n    implementation("${WEARABLE_DEP}")`,
      );
    }
    return cfg;
  });
}

function withManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    if (!Array.isArray(app.service)) app.service = [];
    if (!app.service.some((s) => s.$ && s.$['android:name'] === '.WearListenerService')) {
      app.service.push({
        $: { 'android:name': '.WearListenerService', 'android:exported': 'true' },
        'intent-filter': [{
          action: [{ $: { 'android:name': 'com.google.android.gms.wearable.MESSAGE_RECEIVED' } }],
          data: [{ $: { 'android:scheme': 'wear', 'android:host': '*', 'android:pathPrefix': '/sapp2' } }],
        }],
      });
    }
    return cfg;
  });
}

function withPackageRegistration(config) {
  return withMainApplication(config, (cfg) => {
    cfg.modResults.contents = mergeContents({
      tag: 'sapp2-wear-sync-package',
      src: cfg.modResults.contents,
      newSrc: '              add(WearSyncPackage())',
      anchor: /\/\/\s*add\(MyReactNativePackage\(\)\)/,
      offset: 1,
      comment: '              //',
    }).contents;
    return cfg;
  });
}

module.exports = function withWearSync(config) {
  config = withSources(config);
  config = withDependency(config);
  config = withManifest(config);
  config = withPackageRegistration(config);
  return config;
};
