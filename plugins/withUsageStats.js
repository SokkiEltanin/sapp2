function withSources(config) {
  return withDangerousMod(config, ['android', async (cfg) => {
    const pkg = (cfg.android && cfg.android.package) || 'com.sokki.sapp2';
    const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'java', ...pkg.split('.'));
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'UsageStatsModule.kt'), moduleKotlin(pkg), 'utf8');
    fs.writeFileSync(path.join(dir, 'UsageStatsPackage.kt'), packageKotlin(pkg), 'utf8');
    return cfg;
  }]);
}

// Uprawnienia: PACKAGE_USAGE_STATS jest "chronione" (lint ProtectedPermissions) → tools:ignore.
function withPermissions(config) {
  return withAndroidManifest(config, (cfg) => {
    const m = cfg.modResults.manifest;
    m.$ = m.$ || {};
    if (!m.$['xmlns:tools']) m.$['xmlns:tools'] = 'http://schemas.android.com/tools';
    m['uses-permission'] = m['uses-permission'] || [];
    const add = (name, extra) => {
      if (m['uses-permission'].some((p) => p.$ && p.$['android:name'] === name)) return;
      m['uses-permission'].push({ $: { 'android:name': name, ...extra } });
    };
    add('android.permission.PACKAGE_USAGE_STATS', { 'tools:ignore': 'ProtectedPermissions' });
    add('android.permission.QUERY_ALL_PACKAGES', { 'tools:ignore': 'QueryAllPackagesPermission' });
    return cfg;
  });
}

function withPackageRegistration(config) {
  return withMainApplication(config, (cfg) => {
    cfg.modResults.contents = mergeContents({
      tag: 'sapp2-usage-stats-package',
      src: cfg.modResults.contents,
      newSrc: '              add(UsageStatsPackage())',
      anchor: /\/\/\s*add\(MyReactNativePackage\(\)\)/,
      offset: 1,
      comment: '              //',
    }).contents;
    return cfg;
  });
}

module.exports = function withUsageStats(config) {
  return withPackageRegistration(withPermissions(withSources(config)));
};
