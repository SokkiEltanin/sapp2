// Czas z telefonem (2026-11-22, user: "statystyki użycia innych aplikacji, ilość włączeń
// telefonu dziennie"). Android UsageStatsManager — wymaga specjalnego dostępu "Dostęp do
// danych o użyciu" (Ustawienia systemu, nie zwykłe okienko zgody) + QUERY_ALL_PACKAGES (nazwy
// i ikony innych appek od Androida 11). Moduł "UsageStats":
//  • hasAccess() — synchronicznie, czy user przyznał dostęp;
//  • openAccessSettings() — ekran systemowy z przełącznikiem;
//  • getDays(json "[[start,end],…]") → Promise<string> JSON [{s,total,unlocks,screenOns,first,
//    apps:[{p,l,ms,n,c}],hours[24],longest}] — liczone ze zdarzeń (wznowienie/pauza appki,
//    ekran wł./wył., odblokowanie), bez ekranu głównego i paska systemu;
//  • getIcons(json ["pkg",…]) → Promise<string> JSON {pkg: "data:image/png;base64,…"}.
// JS: src/services/screenTime.ts (`?.` — stary APK = brak modułu = kafel z instrukcją).
// UWAGA: w szablonach Kotlina nie używać backticków ani dolara z klamrą (to JS template string).
const { withDangerousMod, withMainApplication, withAndroidManifest } = require('@expo/config-plugins');
const { mergeContents } = require('@expo/config-plugins/build/utils/generateCode');
const path = require('path');
const fs = require('fs');

function moduleKotlin(pkg) {
  return `package ${pkg}

import android.app.AppOpsManager
import android.app.usage.UsageEvents
import android.app.usage.UsageStatsManager
import android.content.Context
import android.content.Intent
import android.content.pm.ApplicationInfo
import android.content.pm.PackageManager
import android.graphics.Bitmap
import android.graphics.Canvas
import android.net.Uri
import android.os.Build
import android.os.Process
import android.provider.Settings
import android.util.Base64
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod
import org.json.JSONArray
import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.util.Calendar

// Auto-generated by plugins/withUsageStats.js — do not edit here.
class UsageStatsModule(private val ctx: ReactApplicationContext) : ReactContextBaseJavaModule(ctx) {
  override fun getName(): String = "UsageStats"

  @ReactMethod(isBlockingSynchronousMethod = true)
  fun hasAccess(): Boolean {
    return try {
      val ops = ctx.getSystemService(Context.APP_OPS_SERVICE) as AppOpsManager
      val mode = if (Build.VERSION.SDK_INT >= 29)
        ops.unsafeCheckOpNoThrow(AppOpsManager.OPSTR_GET_USAGE_STATS, Process.myUid(), ctx.packageName)
      else
        ops.checkOpNoThrow(AppOpsManager.OPSTR_GET_USAGE_STATS, Process.myUid(), ctx.packageName)
      mode == AppOpsManager.MODE_ALLOWED
    } catch (e: Throwable) { false }
  }

  @ReactMethod
  fun openAccessSettings() {
    val withPkg = Intent(Settings.ACTION_USAGE_ACCESS_SETTINGS).setData(Uri.parse("package:" + ctx.packageName)).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    try { ctx.startActivity(withPkg) } catch (e: Throwable) {
      try { ctx.startActivity(Intent(Settings.ACTION_USAGE_ACCESS_SETTINGS).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)) } catch (x: Throwable) {}
    }
  }

  private fun homePackages(): Set<String> {
    val out = HashSet<String>()
    out.add("com.android.systemui")
    out.add("android")
    try {
      val i = Intent(Intent.ACTION_MAIN).addCategory(Intent.CATEGORY_HOME)
      for (r in ctx.packageManager.queryIntentActivities(i, 0)) out.add(r.activityInfo.packageName)
    } catch (e: Throwable) {}
    return out
  }

  private fun labelOf(pm: PackageManager, p: String): Pair<String, Int> {
    return try {
      val ai: ApplicationInfo = pm.getApplicationInfo(p, 0)
      val cat = if (Build.VERSION.SDK_INT >= 26) ai.category else -1
      Pair(pm.getApplicationLabel(ai).toString(), cat)
    } catch (e: Throwable) { Pair(p, -1) }
  }

  // Sesja [a, b) rozłożona na godziny zegara (czas lokalny).
  private fun addHours(hours: LongArray, a: Long, b: Long) {
    var t = a
    val cal = Calendar.getInstance()
    while (t < b) {
      cal.timeInMillis = t
      val h = cal.get(Calendar.HOUR_OF_DAY)
      cal.set(Calendar.MINUTE, 0); cal.set(Calendar.SECOND, 0); cal.set(Calendar.MILLISECOND, 0)
      cal.add(Calendar.HOUR_OF_DAY, 1)
      val next = Math.min(b, cal.timeInMillis)
      hours[h] += next - t
      t = next
    }
  }

  private fun day(usm: UsageStatsManager, pm: PackageManager, home: Set<String>, s: Long, e: Long): JSONObject {
    val events = usm.queryEvents(s, e)
    val ev = UsageEvents.Event()
    val open = HashMap<String, Long>()      // pakiet/aktywność → początek
    val seen = HashSet<String>()
    val time = HashMap<String, Long>()
    val launches = HashMap<String, Int>()
    val hours = LongArray(24)
    var unlocks = 0
    var screenOns = 0
    var first = 0L
    var lastPkg: String? = null
    var longPkg = ""
    var longMs = 0L
    fun close(key: String, a: Long, b: Long) {
      val p = key.substringBefore('/')
      if (b <= a || home.contains(p)) return
      time[p] = (time[p] ?: 0L) + (b - a)
      addHours(hours, a, b)
      if (b - a > longMs) { longMs = b - a; longPkg = p }
    }
    while (events.hasNextEvent()) {
      events.getNextEvent(ev)
      val t = ev.timeStamp
      val p = ev.packageName ?: ""
      when (ev.eventType) {
        UsageEvents.Event.ACTIVITY_RESUMED -> {
          val key = p + "/" + (ev.className ?: "")
          if (!open.containsKey(key)) open[key] = t
          seen.add(key)
          if (!home.contains(p) && p != lastPkg) launches[p] = (launches[p] ?: 0) + 1
          lastPkg = p
        }
        UsageEvents.Event.ACTIVITY_PAUSED, 23 -> {
          val key = p + "/" + (ev.className ?: "")
          val st = open.remove(key) ?: (if (!seen.contains(key)) s else null)
          seen.add(key)
          if (st != null) close(key, st, t)
        }
        15 -> screenOns++
        16 -> {
          for ((k, st) in open) close(k, st, t)
          open.clear()
          lastPkg = null
        }
        18 -> { unlocks++; if (first == 0L) first = t }
      }
    }
    val end = Math.min(e, System.currentTimeMillis())
    for ((k, st) in open) close(k, st, end)

    val apps = JSONArray()
    val pkgs = HashSet<String>(time.keys)
    pkgs.addAll(launches.keys)
    var total = 0L
    for (p in pkgs) {
      if (home.contains(p)) continue
      val ms = time[p] ?: 0L
      total += ms
      val (label, cat) = labelOf(pm, p)
      apps.put(JSONObject().put("p", p).put("l", label).put("ms", ms).put("n", launches[p] ?: 0).put("c", cat))
    }
    val hj = JSONArray()
    for (h in hours) hj.put(h)
    val o = JSONObject().put("s", s).put("total", total).put("unlocks", unlocks).put("screenOns", screenOns)
      .put("first", first).put("apps", apps).put("hours", hj)
    if (longMs > 0) o.put("longest", JSONObject().put("p", longPkg).put("l", labelOf(pm, longPkg).first).put("ms", longMs))
    return o
  }

  @ReactMethod
  fun getDays(windows: String, promise: Promise) {
    Thread {
      try {
        if (!hasAccess()) { promise.reject("no_access", "Brak dostępu do danych o użyciu"); return@Thread }
        val usm = ctx.getSystemService(Context.USAGE_STATS_SERVICE) as UsageStatsManager
        val pm = ctx.packageManager
        val home = homePackages()
        val arr = JSONArray(windows)
        val out = JSONArray()
        for (i in 0 until arr.length()) {
          val w = arr.getJSONArray(i)
          out.put(day(usm, pm, home, w.getLong(0), w.getLong(1)))
        }
        promise.resolve(out.toString())
      } catch (e: Throwable) { promise.reject("usage_error", e.message ?: "błąd odczytu", e) }
    }.start()
  }

  @ReactMethod
  fun getIcons(pkgs: String, promise: Promise) {
    Thread {
      try {
        val pm = ctx.packageManager
        val arr = JSONArray(pkgs)
        val out = JSONObject()
        val size = 72
        for (i in 0 until arr.length()) {
          val p = arr.getString(i)
          try {
            val d = pm.getApplicationIcon(p)
            val bmp = Bitmap.createBitmap(size, size, Bitmap.Config.ARGB_8888)
            val c = Canvas(bmp)
            d.setBounds(0, 0, size, size)
            d.draw(c)
            val bos = ByteArrayOutputStream()
            bmp.compress(Bitmap.CompressFormat.PNG, 100, bos)
            out.put(p, "data:image/png;base64," + Base64.encodeToString(bos.toByteArray(), Base64.NO_WRAP))
          } catch (e: Throwable) {}
        }
        promise.resolve(out.toString())
      } catch (e: Throwable) { promise.reject("icon_error", e.message ?: "błąd ikon", e) }
    }.start()
  }
}
`;
}

